#!/usr/bin/env python3
"""Build the paste bundles in scripts/gov/paste from scripts/paste_bundles.json.

A bundle is one PowerShell text (Windows PowerShell 5.1) that the PFM copies from its raw page and pastes into
Windows PowerShell ISE, then runs with F5 (ISSM approved in writing, PFM 2026-11-12). It:
  1. asks for the DODID (Enter = profile folder), as the runners do;
  2. makes each task folder under C:\\Users\\<DODID>\\OneDrive - United States Air Force\\90-161.Z if it is missing;
  3. writes every file (text: same content, saved as UTF-8 with BOM and CRLF; binary: byte-exact from base64), replacing
     older copies; the WROTE line shows src-sha256 = the first 12 hex of the repo file's sha256 (LF, no BOM);
  4. runs the runner's text in-process with -Id and -NoPause.
Text files are embedded as readable single-quoted here-strings, so the PFM and the ISSM can read the code.
Usage: python3 scripts/build_paste_bundles.py [--check]   (--check: exit 1 if a bundle is out of date)
"""
import base64, hashlib, json, sys, textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEXT = {'.ps1', '.json', '.txt', '.md', '.csv'}


def here(text):
    text = text.replace('\r\n', '\n')
    if text.endswith('\n'):
        text = text[:-1]
    for line in text.split('\n'):
        if line.startswith("'@"):
            raise SystemExit("cannot embed: a line starts with '@")
    if any(ord(c) > 127 for c in text):
        raise SystemExit('cannot embed: non-ASCII text (5.1 reads pasted text as typed; keep sources ASCII)')
    return "@'\n" + text + "\n'@"


def build(b):
    parts = []
    for f in b['files']:
        src = ROOT / f['src']
        data = src.read_bytes()
        name = src.name
        sha = hashlib.sha256(data).hexdigest()[:12]
        if src.suffix.lower() in TEXT:
            body = here(data.decode('ascii'))
            kind = 'text'
        else:
            b64 = base64.b64encode(data).decode('ascii')
            body = "@'\n" + '\n'.join(textwrap.wrap(b64, 100)) + "\n'@"
            kind = 'base64'
        parts.append(
            "$files += @{ Dir = '%s'; Name = '%s'; Kind = '%s'; Sha = '%s'; Data = %s }"
            % (f['dir'], name, kind, sha, body))
    run = b['run']
    head = '''<#
  90-161.Z paste bundle: %(title)s. GENERATED by scripts/build_paste_bundles.py from scripts/paste_bundles.json; do not edit.
  How to run: open Windows PowerShell ISE, File > New, paste all of this text into the script pane, press F5.
  It asks for the DODID (Enter = this computer's profile folder), makes the task folders under
  C:\\Users\\<DODID>\\OneDrive - United States Air Force\\90-161.Z if they are missing, writes the files below
  (it replaces older copies of the same name), then runs %(run)s.
  It needs no download, no admin rights and changes nothing outside the 90-161.Z folder.
#>
$bundle = '%(title)s'
$files = @()
''' % {'title': b['title'], 'run': run['name']}
    tail = r'''
$runDir = '%(dir)s'
$runName = '%(name)s'
try {
  $ErrorActionPreference = 'Stop'
  $profileLeaf = ''
  if ($env:USERPROFILE) { $profileLeaf = Split-Path -Leaf $env:USERPROFILE }
  $id = ([string](Read-Host 'DODID (press Enter to use this computer''s profile folder)')).Trim()
  if (-not $id) { $id = $profileLeaf }
  if ($id -notmatch '^[A-Za-z0-9._-]{4,}$') { throw 'DODID not valid: use the folder name under C:\Users (4 or more letters, digits, dot, dash or underscore).' }
  $base = Join-Path (Join-Path 'C:\Users' $id) 'OneDrive - United States Air Force\90-161.Z'
  $oneDrive = Split-Path -Parent $base
  if (-not (Test-Path -LiteralPath $oneDrive -PathType Container)) { throw 'FOLDER not found: C:\Users\<DODID>\OneDrive - United States Air Force. Check the DODID.' }
  $utf8Bom = New-Object System.Text.UTF8Encoding $true
  foreach ($f in $files) {
    $dir = Join-Path $base $f.Dir
    if (-not (Test-Path -LiteralPath $dir -PathType Container)) { [void](New-Item -ItemType Directory -Path $dir -Force) }
    $path = Join-Path $dir $f.Name
    if ($f.Kind -eq 'text') {
      $text = ($f.Data -replace "`r?`n", "`r`n") + "`r`n"
      [System.IO.File]::WriteAllText($path, $text, $utf8Bom)
    } else {
      [System.IO.File]::WriteAllBytes($path, [System.Convert]::FromBase64String(($f.Data -replace '\s', '')))
    }
    Write-Host ('WROTE ' + $f.Dir + '\' + $f.Name + ' src-sha256=' + $f.Sha)
  }
  $runText = ($files | Where-Object { $_.Dir -eq $runDir -and $_.Name -eq $runName } | Select-Object -First 1).Data
  Write-Host ('RUN ' + $runName + ' (' + $bundle + ')')
  Push-Location
  try { & ([scriptblock]::Create($runText)) -Id $id -NoPause } finally { Pop-Location }
} catch {
  $msg = [string]$_
  $secret = @($id, $profileLeaf, $env:USERNAME) | Where-Object { $_ -and $_.Length -ge 4 } | Sort-Object -Unique | Sort-Object Length -Descending
  foreach ($x in $secret) { $msg = $msg -replace [regex]::Escape($x), '<DODID>' }
  Write-Host ''
  Write-Host ('STOPPED: ' + $msg)
  Write-Host 'Report this STOPPED line.'
}
''' % run
    return head + '\n'.join(parts) + '\n' + tail


def main():
    check = '--check' in sys.argv
    m = json.loads((ROOT / 'scripts/paste_bundles.json').read_text())
    stale = 0
    for b in m['bundles']:
        out = ROOT / b['out']
        text = build(b)
        if check:
            if not out.exists() or out.read_bytes() != text.encode('ascii'):
                print('STALE ' + b['out']); stale += 1
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(text.encode('ascii'))
        print('BUILT %s bytes=%d files=%d' % (b['out'], len(text), len(b['files'])))
    if check:
        print('PASTE bundles=%d stale=%d' % (len(m['bundles']), stale))
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
