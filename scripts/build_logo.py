#!/usr/bin/env python3
"""Build the 90-161.Z logo (assets/logo/*.svg): a still frame of the owner's
square-in-a-square theme mark with a Greek rho in the center. A square frame and a square turned 45 degrees weave over and
under each other at the 8 crossings. White and light blue strokes, made for blue
backgrounds. Run: python3 scripts/build_logo.py then node scripts/render_logo.js for the PNGs."""
import math, pathlib

S, D = 29.0, 39.0          # frame half-side; diamond half-diagonal
SW, GAP = 5.0, 1.6         # stroke width; clear space each side of the over-stroke
OUTER, INNER, TILE = "#FFFFFF", "#CFE0FF", "#0B3D91"
VB = 45                    # viewBox half-size (diamond tip + miter = 42.5)
H = SW / 2 * math.sqrt(2) + SW / 2 + GAP + 0.5   # half-length of each cut: clears the whole under-stroke

def rot(p, k):             # rotate (x, y) by k * 90 degrees
    x, y = p
    for _ in range(k):
        x, y = -y, x
    return x, y

c = D - S                  # crossing offset from edge midpoint
diamond_over, frame_over = [], []
for k in range(4):         # pinwheel: alternate over/under along both paths
    diamond_over.append((rot((-c, -S), k), rot((-1, 1), k)))   # cut runs along diamond side
    frame_over.append((rot((c, -S), k), rot((1, 0), k)))       # cut runs along frame edge

def cuts(items):
    out = []
    for (x, y), (dx, dy) in items:
        n = math.hypot(dx, dy); dx, dy = dx / n * H, dy / n * H
        out.append(f'<line x1="{x-dx:.2f}" y1="{y-dy:.2f}" x2="{x+dx:.2f}" y2="{y+dy:.2f}"/>')
    return "".join(out)

frame = f'M{-S} {-S}H{S}V{S}H{-S}Z'
diamond = f'M0 {-D}L{D} 0L0 {D}L{-D} 0Z'
gap_w = SW + 2 * GAP

# Center symbol: Greek rho, outline copied once from FreeSerif (GNU FreeFont, GPL with font
# exception) so the logo needs no installed font. Font units: 1000/em, ink box x 50..487, y -221..461.
RHO = ("M272 461Q371 461 429.0 397.0Q487 333 487 233Q487 129 427.5 59.5Q368 -10 266 -10Q197 -10 143 33"
       "Q143 12 144.0 -29.0Q145 -70 145 -90Q145 -174 134 -221H50Q51 -212 54.5 -195.0Q58 -178 60.0 -164.0"
       "Q62 -150 62 -137Q62 -83 59.5 24.5Q57 132 57 186Q57 239 69.0 286.5Q81 334 105.5 374.0"
       "Q130 414 173.0 437.5Q216 461 272 461ZM262 432Q138 432 138 239Q138 205 146.0 168.5Q154 132 170.0 97.5"
       "Q186 63 215.0 41.0Q244 19 281 19Q314 19 337.5 35.5Q361 52 373.0 80.0Q385 108 390.0 136.5"
       "Q395 165 395 196Q395 232 389.0 268.5Q383 305 369.5 344.0Q356 383 328.0 407.5Q300 432 262 432Z")
RHO_K = 0.04               # scale: ink height 27.3 units
RHO_CY = 1.5               # ink-box center below the mark center; the thin tail sits low, so the bowl reads centered
rho_tx = -(50 + 487) / 2 * RHO_K
rho_ty = RHO_CY + (461 + -221) / 2 * RHO_K
rho = f'<path d="{RHO}" fill="{OUTER}" transform="translate({rho_tx:.2f} {rho_ty:.2f}) scale({RHO_K} {-RHO_K})"/>'

def svg(tile):
    bg = f'<rect x="{-VB}" y="{-VB}" width="{2*VB}" height="{2*VB}" fill="{TILE}"/>' if tile else ""
    m = f'maskUnits="userSpaceOnUse" x="{-VB}" y="{-VB}" width="{2*VB}" height="{2*VB}"'
    full = f'<rect x="{-VB}" y="{-VB}" width="{2*VB}" height="{2*VB}" fill="#fff"/>'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{-VB} {-VB} {2*VB} {2*VB}" width="512" height="512" role="img" aria-label="90-161.Z mark: Greek letter rho inside a square frame and a square turned 45 degrees, woven">
  <!-- Generated by scripts/build_logo.py. Do not hand-edit. -->
  {bg}<defs>
    <mask id="cut-diamond" {m}>{full}<g stroke="#000" stroke-width="{gap_w}">{cuts(frame_over)}</g></mask>
    <mask id="cut-frame" {m}>{full}<g stroke="#000" stroke-width="{gap_w}">{cuts(diamond_over)}</g></mask>
  </defs>
  <path d="{diamond}" fill="none" stroke="{INNER}" stroke-width="{SW}" mask="url(#cut-diamond)"/>
  <path d="{frame}" fill="none" stroke="{OUTER}" stroke-width="{SW}" mask="url(#cut-frame)"/>
  {rho}
</svg>
'''

d = pathlib.Path(__file__).resolve().parent.parent / "assets" / "logo"
d.mkdir(parents=True, exist_ok=True)
(d / "90161Z-mark.svg").write_text(svg(False))
(d / "90161Z-mark-tile.svg").write_text(svg(True))
print("wrote", d / "90161Z-mark.svg", d / "90161Z-mark-tile.svg")
