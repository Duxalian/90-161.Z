  if ([bool](Get-PartValue $parts 'paperworkReduction')) { $s.Add($script:Stmt.Paperwork) }          # 4.5.5.5
  $pun = [string](Get-PartValue $parts 'punitiveScope')
  if ($pun) {                                                                                         # 4.5.5.6
